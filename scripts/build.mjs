/**
 * dsh-onestep 构建脚本：把 src/client/** 打成 DSH 客户端插件 bundle（根 client.js）。
 *
 * 产物契约（照 DSH 0.2.2-rc.1 官方 client bundle 与已发布第三方包）：
 *   window.__ModuleLoader__.load({ id:'dsh-onestep', factory(require){ ... return module.exports } })
 * - 顶层必须是 DSH loader 的 registration 调用；factory 内才产生副作用；
 * - baseline 共享模块走 factory 的 require（external 表），不得打进 bundle；
 * - 产物放在仓库根（package.json 的 exports["./client"] 指向 ./client.js）。
 *
 * 用法：node scripts/build.mjs   （构建）+ node scripts/build.mjs --check（只校验语法）
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = path.join(ROOT, 'src', 'client', 'index.js')
const OUT = path.join(ROOT, 'client.js')

/** DSH client baseline 共享模块表（platform.ts；11 项，运行时由宿主提供）。 */
const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const BANNER = `/* dsh-onestep client bundle — generated by scripts/build.mjs, do not edit by hand. */
window.__ModuleLoader__.load({
  id: 'dsh-onestep',
  factory: function (require) {
    var module = { exports: {} };
    var exports = module.exports;
`
const FOOTER = `
    return module.exports;
  },
});
`

async function main() {
  const checkOnly = process.argv.includes('--check')
  if (!fs.existsSync(ENTRY)) throw new Error('missing entry: ' + ENTRY)
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    charset: 'utf8',
    legalComments: 'none',
    sourcemap: false,
    minify: false,
    external: PLATFORM_MODULES,
    logLevel: 'warning',
  })
  const body = result.outputFiles[0].text
  const bundle = BANNER + body + FOOTER
  if (checkOnly) {
    console.log('[build] --check: ' + bundle.length + ' bytes OK')
    return
  }
  fs.writeFileSync(OUT, bundle, 'utf8')
  console.log('[build] wrote ' + path.relative(ROOT, OUT) + ' (' + bundle.length + ' bytes, esbuild ' + esbuild.version + ')')
}

main().catch((e) => {
  console.error('[build] FAILED: ' + ((e && e.stack) || e))
  process.exit(1)
})
